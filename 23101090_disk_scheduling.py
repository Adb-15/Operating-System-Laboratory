def scan(requests, head, direction="left", disk_size=101):
    left = sorted([r for r in requests if r < head], reverse=True)
    right = sorted([r for r in requests if r > head])

    if direction == "left":
        if 0 not in left:
            left.append(0)
        seq = left + right
    else:
        max_track = disk_size - 1
        if max_track not in right:
            right.append(max_track)
        seq = right + left

    total_seek = 0
    curr = head
    for track in seq:
        total_seek += abs(track - curr)
        curr = track

    return seq, total_seek


