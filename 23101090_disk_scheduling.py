def sstf(requests, head):
    sequence = []
    total_seek = 0
    queue = requests.copy()
    current = head

    while queue:
        closest = min(queue, key=lambda x: abs(x - current))
        total_seek += abs(closest - current)
        sequence.append(closest)
        current = closest
        queue.remove(closest)

    return sequence, total_seek

