def calculate_fcfs(processes, arrival_times, burst_times):
    n = len(processes)
    ct = [0] * n
    tat = [0] * n
    wt = [0] * n

    current_time = 0
    for i in range(n):

        if current_time < arrival_times[i]:
            current_time = arrival_times[i]

        current_time += burst_times[i]
        ct[i] = current_time
        tat[i] = ct[i] - arrival_times[i]
        wt[i] = tat[i] - burst_times[i]

    avg_tat = sum(tat) / n
    avg_wt = sum(wt) / n

    return ct, tat, wt, avg_tat, avg_wt


processes = ['p1', 'p2', 'p3', 'p4']
at = [0, 2, 3, 5]
bt = [2, 3, 3, 2]

ct, tat, wt, avg_tat, avg_wt = calculate_fcfs(processes, at, bt)

print("Process\tAT\tBT\tCT\tTAT\tWT")
for i in range(len(processes)):
    print(f"{processes[i]}\t{at[i]}\t{bt[i]}\t{ct[i]}\t{tat[i]}\t{wt[i]}")

print(f"\nAverage Turnaround Time: {avg_tat}")
print(f"Average Waiting Time: {avg_wt}")